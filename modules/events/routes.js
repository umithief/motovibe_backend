import { Router } from 'express';
import { checkUser } from '../../middleware/authMiddleware.js';
import * as controller from './controller.js';
const router = Router();
router.get('/', checkUser, controller.listEvents);
router.get('/stats', controller.getEventStats);
router.get('/featured', controller.getFeaturedEvents);
router.get('/my', checkUser, controller.getMyEvents);
router.get('/:id', checkUser, controller.getEvent);
router.post('/', checkUser, controller.createEvent);
router.put('/:id', checkUser, controller.updateEvent);
router.delete('/:id', checkUser, controller.deleteEvent);
router.post('/:id/cancel', checkUser, controller.cancelEvent);
router.post('/:id/join', checkUser, controller.joinEvent);
router.post('/:id/leave', checkUser, controller.leaveEvent);
router.post('/:id/start', checkUser, controller.startEvent);
router.post('/:id/finish', checkUser, controller.finishEvent);
router.post('/:id/live-location', checkUser, controller.updateEventLocation);
router.get('/:id/live', checkUser, controller.getEventLive);
router.post('/:id/message', checkUser, controller.sendEventMessage);
export default router;
